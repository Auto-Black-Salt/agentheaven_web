#!/usr/bin/env python3
"""Pre-render the Hungarian and German landing pages (hu/index.html, de/index.html) from index.html.

index.html stays the single source: its inline dictionary (var T = {...}) supplies every translated string.
Run after any copy change:  python3 scripts/build-i18n.py
Search engines then get real, crawlable HTML for each language, with self-referencing canonicals.
"""
import html, json, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = open(os.path.join(ROOT, "index.html"), encoding="utf-8").read()

# 1. The dictionary, evaluated by node (it is a JS object literal).
start = SRC.index("  var T = {")
end = SRC.index("\n  };", start) + 5
js = SRC[start:end].strip().replace("var T =", "const T =", 1)
T = json.loads(subprocess.run(["node", "-e", js + "\nconsole.log(JSON.stringify(T))"], capture_output=True, text=True, check=True).stdout)

LOCALE = {"en": "en_GB", "hu": "hu_HU", "de": "de_DE"}
BASE = "https://agentheaven.ai"

def esc(s): return html.escape(s, quote=False)
def esc_attr(s): return html.escape(s, quote=True)

def build(lang):
    d, en = T[lang], T["en"]
    t = lambda k: d.get(k) or en.get(k) or ""
    s = SRC

    # visible text and attributes
    s = re.sub(r'(<([a-z0-9]+)[^>]*?data-i18n="([^"]+)"[^>]*)()>([^<]*)</', lambda m: (
        m.group(1) + ">" + (esc(t(m.group(3))) or m.group(5)) + "</"), s)
    def attr(name, key_attr):
        def r(m):
            tag = m.group(0); k = re.search(key_attr + r'="([^"]+)"', tag).group(1); v = t(k)
            if not v: return tag
            return re.sub(r'\b' + name + r'="[^"]*"', name + '="' + esc_attr(v) + '"', tag, count=1) if re.search(r'\b' + name + '="', tag) else tag.replace(key_attr, name + '="' + esc_attr(v) + '" ' + key_attr, 1)
        return r
    s = re.sub(r'<[a-z0-9]+[^>]*data-i18n-aria-label="[^"]+"[^>]*>', attr("aria-label", "data-i18n-aria-label"), s)
    s = re.sub(r'<[a-z0-9]+[^>]*data-i18n-placeholder="[^"]+"[^>]*>', attr("placeholder", "data-i18n-placeholder"), s)

    # head
    title, desc = t("meta.title"), t("meta.description")
    s = s.replace('<html lang="en">', f'<html lang="{lang}">', 1)
    s = re.sub(r"<title>.*?</title>", lambda m: f"<title>{esc(title)}</title>", s, count=1)
    s = re.sub(r'(<meta name="description" content=")[^"]*(")', lambda m: m.group(1) + esc_attr(desc) + m.group(2), s, count=1)
    for prop, val in (("og:title", title), ("og:description", desc)):
        s = re.sub(rf'(<meta property="{prop}" content=")[^"]*(")', lambda m: m.group(1) + esc_attr(val) + m.group(2), s, count=1)
    for nm, val in (("twitter:title", title), ("twitter:description", desc)):
        s = re.sub(rf'(<meta name="{nm}" content=")[^"]*(")', lambda m: m.group(1) + esc_attr(val) + m.group(2), s, count=1)
    url = f"{BASE}/{lang}/"
    s = s.replace('<link rel="canonical" href="https://agentheaven.ai/" />', f'<link rel="canonical" href="{url}" />')
    s = s.replace('<meta property="og:url" content="https://agentheaven.ai/" />', f'<meta property="og:url" content="{url}" />')
    s = s.replace('<meta property="og:locale" content="en_GB" />', f'<meta property="og:locale" content="{LOCALE[lang]}" />')
    others = [l for l in ("en", "hu", "de") if l != lang]
    alt = "\n".join(f'  <meta property="og:locale:alternate" content="{LOCALE[l]}" />' for l in others)
    s = re.sub(r'  <meta property="og:locale:alternate" content="hu_HU" />\n  <meta property="og:locale:alternate" content="de_DE" />', alt, s, count=1)

    # JSON-LD: localise the FAQ
    m = re.search(r'(<script type="application/ld\+json">)(.*?)(</script>)', s, re.S)
    ld = json.loads(m.group(2))
    for node in ld["@graph"]:
        if node.get("@type") == "FAQPage":
            items = node["mainEntity"]
            for i, q in enumerate(items, 1):
                assert q["name"] == en[f"faq.{i}.q"], (i, q["name"])
                q["name"] = t(f"faq.{i}.q"); q["acceptedAnswer"]["text"] = t(f"faq.{i}.a")
            node["inLanguage"] = lang
        if node.get("@type") == "Service":
            node["inLanguage"] = lang
    s = s[:m.start(2)] + "\n  " + json.dumps(ld, ensure_ascii=False, indent=2).replace("\n", "\n  ") + "\n  " + s[m.end(2):]

    # relative URLs -> root-absolute (the page lives one level down)
    s = re.sub(r'\b(href|src)="(?!https?:|#|/|\?|mailto:|tel:|data:|javascript:)([^"]*)"',
               lambda m: f'{m.group(1)}="/{m.group(2)}"', s)
    s = s.replace('href="/index.html"', f'href="/{lang}/"')
    s = s.replace("url(fonts/", "url(/fonts/")
    s = s.replace('<link rel="canonical"', f'<!-- GENERATED by scripts/build-i18n.py from index.html. Do not edit by hand. -->\n  <link rel="canonical"', 1)
    out = os.path.join(ROOT, lang)
    os.makedirs(out, exist_ok=True)
    open(os.path.join(out, "index.html"), "w", encoding="utf-8").write(s)
    print("wrote", lang + "/index.html", len(s))

for l in ("hu", "de"):
    build(l)
